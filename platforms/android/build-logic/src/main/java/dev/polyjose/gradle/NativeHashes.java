package dev.polyjose.gradle;

import java.io.File;
import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.Map;
import java.util.SortedMap;
import java.util.TreeMap;
import javax.inject.Inject;
import org.gradle.api.DefaultTask;
import org.gradle.api.GradleException;
import org.gradle.api.file.ConfigurableFileCollection;
import org.gradle.api.file.DirectoryProperty;
import org.gradle.api.file.FileSystemOperations;
import org.gradle.api.tasks.InputFiles;
import org.gradle.api.tasks.OutputDirectory;
import org.gradle.api.tasks.PathSensitive;
import org.gradle.api.tasks.PathSensitivity;
import org.gradle.api.tasks.TaskAction;

/**
 * Writes {@code dev/polyjose/PolyjoseNativeHashes.kt}: the SHA-256 of every native library an
 * artifact packs, keyed by its JNA resource path {@code <prefix>/<library>} (feature 0008 F05,
 * security audit M1; ADR 0033 §3a, §4). The object is compiled into the artifact's own classes,
 * so whoever swaps a library in the jar (or plants one earlier on the class path) cannot also
 * change the hash it is checked against; a manifest attribute would travel with the swapped jar.
 * {@code PolyjoseNativeLoader} reads it on the JVM.
 *
 * <p>{@link #getNatives()} is the directory tree the jar packs, laid out {@code
 * <prefix>/<library>} (polyjose-jvm's {@code assembleJarNatives}); every file in it must be at
 * that depth. The Android library leaves it empty: the AAR's libraries load from the APK's
 * linker namespace, which the loader does not hash (security audit I2), and the object then
 * holds an empty map.
 */
public abstract class NativeHashes extends DefaultTask {
    /** The generated file, relative to {@link #getOutputDir()}. */
    public static final String SOURCE_PATH = "dev/polyjose/PolyjoseNativeHashes.kt";

    private final FileSystemOperations fs;

    @Inject
    public NativeHashes(FileSystemOperations fs) {
        this.fs = fs;
    }

    /** The tree of {@code <prefix>/<library>} files the artifact packs (empty for the AAR). */
    @InputFiles
    @PathSensitive(PathSensitivity.RELATIVE)
    public abstract ConfigurableFileCollection getNatives();

    /** The generated Kotlin source root. */
    @OutputDirectory
    public abstract DirectoryProperty getOutputDir();

    @TaskAction
    public void write() throws IOException {
        SortedMap<String, String> hashes = new TreeMap<>();
        getNatives().getAsFileTree().visit(details -> {
            if (details.isDirectory()) {
                return;
            }
            String path = details.getRelativePath().getPathString();
            if (details.getRelativePath().getSegments().length != 2) {
                throw new GradleException("NativeHashes: " + path + " is not a <prefix>/<library> file");
            }
            if (hashes.put(path, sha256(details.getFile())) != null) {
                throw new GradleException("NativeHashes: " + path + " appears twice");
            }
        });
        File out = getOutputDir().get().getAsFile();
        fs.delete(spec -> spec.delete(out));
        File source = new File(out, SOURCE_PATH);
        Files.createDirectories(source.getParentFile().toPath());
        Files.writeString(source.toPath(), render(hashes));
    }

    /** The Kotlin source for these hashes; the same map always gives the same text. */
    public static String render(SortedMap<String, String> hashes) {
        StringBuilder b = new StringBuilder();
        b.append("// Generated by platforms/android/build-logic NativeHashes (feature 0008 F05). Do not edit.\n");
        b.append("package dev.polyjose\n\n");
        b.append("/**\n");
        b.append(" * The SHA-256 (lowercase hex) of each native library this artifact packs, by JNA resource path\n");
        b.append(" * `<prefix>/<library>`, computed by the build from the exact files the jar packs (security audit\n");
        b.append(" * M1; ADR 0033 §3a, §4). Compiled into the artifact's own classes, so a swapped or shadowing\n");
        b.append(" * library cannot bring its own hash. Empty in the AAR: Android loads from the APK (audit I2).\n");
        b.append(" */\n");
        b.append("internal object PolyjoseNativeHashes {\n");
        if (hashes.isEmpty()) {
            b.append("    val SHA256: Map<String, String> = emptyMap()\n");
        } else {
            b.append("    val SHA256: Map<String, String> = mapOf(\n");
            for (Map.Entry<String, String> e : hashes.entrySet()) {
                b.append("        \"").append(e.getKey()).append("\" to \"").append(e.getValue()).append("\",\n");
            }
            b.append("    )\n");
        }
        b.append("}\n");
        return b.toString();
    }

    private static String sha256(File file) {
        try (InputStream in = Files.newInputStream(file.toPath())) {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            byte[] buffer = new byte[65536];
            for (int n = in.read(buffer); n >= 0; n = in.read(buffer)) {
                digest.update(buffer, 0, n);
            }
            StringBuilder hex = new StringBuilder();
            for (byte x : digest.digest()) {
                hex.append(String.format("%02x", x & 0xff));
            }
            return hex.toString();
        } catch (IOException | NoSuchAlgorithmException e) {
            throw new GradleException("NativeHashes: cannot hash " + file, e);
        }
    }
}
