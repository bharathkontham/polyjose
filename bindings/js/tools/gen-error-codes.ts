/**
 * Generates `src/error-codes.ts` (`ERROR_CODES` and the `ErrorCode` union) from the core's
 * `Error::CODES` in `crates/polyjose/src/error.rs` (ADR 0047: the union is generated, never
 * hand-copied, so a new core code can't be missed).
 *
 * It reads the Rust source as text and never edits `crates/polyjose`. The block it parses is
 *
 * ```rust
 * pub const CODES: &'static [&'static str] = &[
 *     "InvalidBase64",
 *     ...
 * ];
 * ```
 *
 * Run by `npm run build` and `test.sh` as `node tools/gen-error-codes.ts`, through Node's
 * built-in TypeScript type stripping (unflagged since Node 22.18 and 23.6; the build machine
 * runs Node 24). It is also compiled by `tsc`, so the tests import `parseErrorCodes`.
 * Self-contained on purpose: Node's type stripping does not map `./x.js` imports to `.ts`
 * sources, so this file imports nothing local.
 */

const BLOCK = /pub const CODES: &'static \[&'static str\] = &\[([^\]]*)\];/;
const CODE = /^[A-Z][A-Za-z0-9]*$/;

/** The codes of `Error::CODES` in `source` (the text of error.rs), in declaration order. */
export function parseErrorCodes(source: string): string[] {
  const block = BLOCK.exec(source);
  if (block === null) {
    throw new Error("Error::CODES (pub const CODES: &'static [&'static str] = &[...];) not found in error.rs");
  }
  const body = block[1] ?? "";
  const codes: string[] = [];
  for (const raw of body.split(",")) {
    const item = raw.trim();
    if (item === "") continue;
    const m = /^"(.*)"$/.exec(item);
    const code = m?.[1];
    if (code === undefined || !CODE.test(code)) {
      throw new Error(`Error::CODES entry is not a code literal: ${item}`);
    }
    if (codes.includes(code)) throw new Error(`Error::CODES lists ${code} twice`);
    codes.push(code);
  }
  if (codes.length === 0) throw new Error("Error::CODES is empty");
  return codes;
}

/** The TypeScript source of `src/error-codes.ts` for `codes`. */
export function renderErrorCodes(codes: readonly string[]): string {
  const items = codes.map((c) => `  "${c}",\n`).join("");
  return (
    "// GENERATED by tools/gen-error-codes.ts from crates/polyjose/src/error.rs (Error::CODES).\n" +
    "// Do not edit: `npm run build` (or bindings/js/test.sh) regenerates it (ADR 0047).\n\n" +
    "/** The stable error codes of every polyjose binding, in the core's order (ADR 0030 §5). */\n" +
    `export const ERROR_CODES = [\n${items}] as const;\n\n` +
    "/** One stable error code: `PolyjoseError.code` is always one of these (ADR 0030 §5). */\n" +
    "export type ErrorCode = (typeof ERROR_CODES)[number];\n"
  );
}

interface ToolFs {
  readFileSync(path: string, encoding: "utf8"): string;
  writeFileSync(path: string, data: string): void;
  existsSync(path: string): boolean;
  mkdirSync(path: string, options: { recursive: true }): string | undefined;
}
interface ToolPath {
  resolve(...parts: string[]): string;
  dirname(path: string): string;
}
interface ToolProcess {
  readonly argv: readonly string[];
  getBuiltinModule(id: "node:fs"): ToolFs;
  getBuiltinModule(id: "node:path"): ToolPath;
}

const proc = (globalThis as unknown as { process?: ToolProcess }).process;
const script = proc?.argv[1] ?? "";
if (proc !== undefined && /gen-error-codes\.ts$/.test(script)) {
  const fs = proc.getBuiltinModule("node:fs");
  const path = proc.getBuiltinModule("node:path");
  const here = path.dirname(path.resolve(script));
  const errorRs = path.resolve(here, "../../../crates/polyjose/src/error.rs");
  const out = path.resolve(here, "../src/error-codes.ts");
  const text = renderErrorCodes(parseErrorCodes(fs.readFileSync(errorRs, "utf8")));
  fs.mkdirSync(path.dirname(out), { recursive: true });
  if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== text) fs.writeFileSync(out, text);
}
